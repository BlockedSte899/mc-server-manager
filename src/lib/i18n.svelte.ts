const messages: Record<LangCode, Dict> = { en: {}, ru };

export function currentLang(): LangCode {
  return settings.lang === "ru" ? "ru" : "en";
}

/** Translate an English source string into the active UI language.
 * Unknown strings fall back to English (the key itself). */
export function t(key: string, vars?: Record<string, string | number>): string {
  const table = messages[currentLang()];
  let s = table[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Plural helper. Pass the three Russian forms (with {n}) and the English
 * string; the active language decides which is returned, then {n}/vars are
 * interpolated. */
export function pl(
  n: number,
  ruForms: [string, string, string],
  en: string,
  vars?: Record<string, string | number>,
): string {
  const inject = (s: string) => {
    let out = s.replace("{n}", String(n));
    if (vars) {
      for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
    }
    return out;
  };
  if (currentLang() === "en") return inject(en);
  const [one, few, many] = ruForms;
  const m10 = n % 10;
  const m100 = n % 100;
  const form = m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
  return inject(form);
}